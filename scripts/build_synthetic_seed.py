"""Writes supabase/seed/synthetic_a112.sql from the deterministic generator (synthetic data only).

    python scripts/build_synthetic_seed.py
The SQL is idempotent: it inserts the astronaut, its declared menstruation events and its
observations, skipping rows that already exist.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from backend.aegis.medical import synthetic  # noqa: E402

rows = synthetic.rows_for(synthetic.A112, 'review', 112)
biomarkers = sorted({r['biomarker_id'] for r in rows})
packed = [[biomarkers.index(r['biomarker_id']), int(r['measured_at'].timestamp() // 60), r['value'],
           r['context'] or None] for r in rows]
events = [int((synthetic.MISSION_START.timestamp() // 60) + d * 1440) for d in synthetic.MENSTRUATION_DAYS]
sql = f"""-- GENERATED by scripts/build_synthetic_seed.py. Synthetic development data: no real person.
insert into aegis.astronauts (id, code, display_name, sex, cycle_status, usual_cycle_length_days, mission_start, is_synthetic)
values ('{synthetic.A112}', 'A-112', 'Lena Ortiz (sintética)', 'female', 'active', 28, '{synthetic.MISSION_START.isoformat()}', true)
on conflict (code) do nothing;

insert into aegis.mission_events (astronaut_id, kind, started_at, severity, details, source, is_synthetic)
select '{synthetic.A112}', 'menstruation_start', to_timestamp(m * 60), 'info', '{{"declared_by": "astronaut"}}', '{synthetic.SOURCE}', true
from unnest(array{events}::bigint[]) as m
where not exists (select 1 from aegis.mission_events e where e.astronaut_id = '{synthetic.A112}'
                  and e.kind = 'menstruation_start' and e.started_at = to_timestamp(m * 60));

insert into aegis.measurements (astronaut_id, biomarker_id, unit, value, measured_at, source, method, quality, context, is_synthetic)
select '{synthetic.A112}', d.id, d.unit, (r ->> 2)::float8, to_timestamp((r ->> 1)::bigint * 60),
       '{synthetic.SOURCE}', 'synthetic', 'good',
       case when jsonb_typeof(r -> 3) = 'object' then r -> 3 else '{{}}'::jsonb end, true
from jsonb_array_elements('{json.dumps(packed, separators=(",", ":"), ensure_ascii=False)}'::jsonb) as r
join aegis.biomarker_definitions d on d.id = (array{biomarkers})[(r ->> 0)::int + 1]
on conflict (astronaut_id, biomarker_id, measured_at, source) where supersedes_id is null do nothing;
"""
target = ROOT / 'supabase' / 'seed' / 'synthetic_a112.sql'
target.parent.mkdir(exist_ok=True)
target.write_text(sql, encoding='utf-8', newline='\n')
print(target, len(rows), 'observations', len(sql), 'bytes')
