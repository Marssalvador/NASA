"""Builds the reference-catalogue migration from the versioned data files.

The SQL is generated, never hand-edited: data/biomarker_registry.json, data/medical/risk_catalog.json
and data/medical/protocols.json stay the single source of truth.

    python scripts/build_supabase_seed.py supabase/migrations/<version>_aegis_reference_catalog.sql
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ENGINE = ('aegis-rules', '0.1.0')


def lit(value):
    if value is None:
        return 'null'
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, (dict, list)):
        return "'" + json.dumps(value, ensure_ascii=False).replace("'", "''") + "'::jsonb"
    return "'" + str(value).replace("'", "''") + "'"


def rows(table, columns, values, conflict):
    body = ',\n'.join('  (' + ', '.join(lit(v) for v in row) + ')' for row in values)
    return (f'insert into aegis.{table} ({", ".join(columns)}) values\n{body}\n'
            f'on conflict ({conflict}) do nothing;\n')


def main(target: Path):
    registry = json.loads((ROOT / 'data/biomarker_registry.json').read_text(encoding='utf-8'))
    catalog = json.loads((ROOT / 'data/medical/risk_catalog.json').read_text(encoding='utf-8'))
    protocols = json.loads((ROOT / 'data/medical/protocols.json').read_text(encoding='utf-8'))
    docs = catalog['source_documents']
    known = {d['id'] for d in registry}

    out = ['-- GENERATED by scripts/build_supabase_seed.py from data/*.json. Do not edit by hand.',
           '-- Reference catalogue: biomarkers, risks, signal-risk links, documented protocols, rule engine.',
           '']
    out.append(rows('biomarker_definitions',
                    ['id', 'name', 'unit', 'body_system', 'body_region', 'sensing_layer', 'sample_type',
                     'measurement_method', 'expected_frequency_hours', 'sensor_readiness', 'reference_source', 'enabled'],
                    [[d['id'], d['name'], d['unit'], d['body_system'], d['body_region'], d.get('sensing_layer', 1),
                      d['sample_type'], d['measurement_method'], d['expected_frequency'],
                      d.get('sensor_readiness', 'validated'), d['reference_source'], d.get('enabled', True)]
                     for d in registry], 'id'))
    out.append(rows('risk_definitions',
                    ['id', 'name', 'description', 'body_region', 'criteria', 'source_document', 'validation_status'],
                    [[r['id'], r['name'], r['description'], r['body_region'], r['criteria'],
                      docs[r['source_document']], r['validation_status']] for r in catalog['risks']], 'id'))
    links = []
    for r in catalog['risks']:
        for link in r['links']:
            if link['biomarker'] not in known:
                raise SystemExit(f"{r['id']} links unknown biomarker {link['biomarker']}")
            links.append([r['id'], link['biomarker'], link['role'], link['rationale'],
                          docs[r['source_document']], 'document_orientative'])
    out.append(rows('biomarker_risk_links',
                    ['risk_id', 'biomarker_id', 'role', 'rationale', 'source_document', 'evidence_level'],
                    links, 'risk_id, biomarker_id, role'))
    protocol_rows = []
    for p in protocols['protocols']:
        for c in p['countermeasures']:
            protocol_rows.append([
                f"{p['id']}.{c['category']}", p['risk_id'], p['title'], p['trigger_rule'], p['alert_level'],
                c['category'], c['text'], p.get('applies_to', {}),
                f"{p['source_document']} · {p['level_source']}", 'pending_medical_review'])
    out.append(rows('clinical_protocols',
                    ['id', 'risk_id', 'title', 'trigger_rule', 'alert_level', 'category', 'recommendation',
                     'applies_to', 'source_document', 'validation_status'], protocol_rows, 'id'))
    out.append(rows('model_versions', ['name', 'version', 'kind', 'description', 'validation_status'],
                    [[ENGINE[0], ENGINE[1], 'statistical_rules',
                      'Referencia individual robusta + reglas documentadas del usuario. Sin entrenamiento ni '
                      'calibración; no produce probabilidades.', 'demo_unvalidated']], 'name, version'))
    target.write_text('\n'.join(out), encoding='utf-8', newline='\n')
    print(f'{target}: {len(registry)} biomarkers, {len(catalog["risks"])} risks, {len(links)} links, '
          f'{len(protocol_rows)} protocol rows')


if __name__ == '__main__':
    main(Path(sys.argv[1]))
